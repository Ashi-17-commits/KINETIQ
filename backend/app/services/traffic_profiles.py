"""Synthetic (simulated) traffic speed profiles.

Every trace produced here is generated by a seeded pseudo-random process. None of it
is live traffic, GPS, or sensor data, and results must always be labelled as simulated.
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass
from typing import Optional

from app.utils.units import speed_kmh_to_m_s

STEADY = "steady"
FREE_FLOW = "free_flow"
MODERATE_CONGESTION = "moderate_congestion"
STOP_AND_GO = "stop_and_go"

DEFAULT_TRAFFIC_SEED = 0
TIME_STEP_S = 1.0


@dataclass(frozen=True)
class TrafficProfileSpec:
    """Parameters for one synthetic traffic pattern (speeds are fractions of the target speed)."""

    name: str
    description: str
    min_speed_fraction: float
    max_speed_fraction: float
    speed_cap_kmh: Optional[float]
    max_acceleration_m_s2: float
    max_deceleration_m_s2: float
    cruise_hold_s: tuple[float, float]
    stop_probability: float
    stop_idle_s: tuple[float, float]


TRAFFIC_PROFILES: dict[str, TrafficProfileSpec] = {
    FREE_FLOW: TrafficProfileSpec(
        name=FREE_FLOW,
        description="Light traffic: speed drifts within about ±5% of the target with gentle speed changes.",
        min_speed_fraction=0.92,
        max_speed_fraction=1.03,
        speed_cap_kmh=None,
        max_acceleration_m_s2=0.8,
        max_deceleration_m_s2=1.0,
        cruise_hold_s=(30.0, 120.0),
        stop_probability=0.0,
        stop_idle_s=(0.0, 0.0),
    ),
    MODERATE_CONGESTION: TrafficProfileSpec(
        name=MODERATE_CONGESTION,
        description="Moderate congestion: frequent slowdowns to 45–90% of the target speed and occasional brief stops.",
        min_speed_fraction=0.45,
        max_speed_fraction=0.90,
        speed_cap_kmh=None,
        max_acceleration_m_s2=1.2,
        max_deceleration_m_s2=1.8,
        cruise_hold_s=(15.0, 60.0),
        stop_probability=0.10,
        stop_idle_s=(5.0, 20.0),
    ),
    STOP_AND_GO: TrafficProfileSpec(
        name=STOP_AND_GO,
        description="Stop-and-go: repeated launches to low speed (capped at 40 km/h) followed by braking to a standstill.",
        min_speed_fraction=0.20,
        max_speed_fraction=0.60,
        speed_cap_kmh=40.0,
        max_acceleration_m_s2=1.5,
        max_deceleration_m_s2=2.2,
        cruise_hold_s=(5.0, 20.0),
        stop_probability=0.35,
        stop_idle_s=(3.0, 15.0),
    ),
}

SUPPORTED_TRAFFIC_PROFILES = [STEADY, *TRAFFIC_PROFILES.keys()]


@dataclass(frozen=True)
class SpeedTrace:
    """Speeds at step boundaries: len(speeds_m_s) == len(step_durations_s) + 1."""

    profile: str
    seed: int
    target_speed_kmh: float
    speeds_m_s: tuple[float, ...]
    step_durations_s: tuple[float, ...]


def generate_speed_trace(
    profile: str,
    target_speed_kmh: float,
    duration_minutes: float,
    seed: int = DEFAULT_TRAFFIC_SEED,
    time_step_s: float = TIME_STEP_S,
) -> SpeedTrace:
    """
    Build a deterministic, acceleration-limited synthetic speed trace.

    The vehicle chases a sequence of randomly drawn target speeds (and stops, for
    congested profiles), never exceeding the profile's acceleration/deceleration limits.
    """
    if profile not in TRAFFIC_PROFILES:
        raise ValueError(f"Unknown traffic profile: {profile}")
    if duration_minutes < 0 or target_speed_kmh < 0:
        raise ValueError("duration_minutes and target_speed_kmh must be non-negative")

    spec = TRAFFIC_PROFILES[profile]
    rng = random.Random(f"{profile}:{seed}")
    v_target = speed_kmh_to_m_s(target_speed_kmh)
    cap = speed_kmh_to_m_s(spec.speed_cap_kmh) if spec.speed_cap_kmh is not None else math.inf

    def next_segment() -> tuple[float, float]:
        if rng.random() < spec.stop_probability:
            return 0.0, rng.uniform(*spec.stop_idle_s)
        frac = rng.uniform(spec.min_speed_fraction, spec.max_speed_fraction)
        return min(v_target * frac, cap), rng.uniform(*spec.cruise_hold_s)

    total_s = duration_minutes * 60.0
    n_full = int(total_s // time_step_s)
    remainder = total_s - n_full * time_step_s
    durations = [time_step_s] * n_full
    if remainder > 1e-9:
        durations.append(remainder)

    seg_speed, seg_hold = next_segment()
    v = seg_speed  # start already at the first segment's speed (no launch transient)
    speeds = [v]
    for dt in durations:
        if abs(v - seg_speed) < 1e-9:
            seg_hold -= dt
            if seg_hold <= 0:
                seg_speed, seg_hold = next_segment()
        dv = seg_speed - v
        dv = max(-spec.max_deceleration_m_s2 * dt, min(spec.max_acceleration_m_s2 * dt, dv))
        v = max(0.0, v + dv)
        speeds.append(v)

    return SpeedTrace(
        profile=profile,
        seed=seed,
        target_speed_kmh=target_speed_kmh,
        speeds_m_s=tuple(speeds),
        step_durations_s=tuple(durations),
    )
