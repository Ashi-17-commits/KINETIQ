SIMULATED_TRAFFIC_NOTE = (
    "Traffic is a synthetic pattern generated by the KINETIQ simulator from a seeded random process. "
    "It is not live traffic, GPS, or sensor data."
)


def _vehicle_from_dict(data: dict) -> VehicleConfig:
    return VehicleConfig(
        mass_kg=data["mass_kg"],
        rolling_resistance_coefficient=data["rolling_resistance_coefficient"],
        drag_coefficient=data["drag_coefficient"],
        frontal_area_m2=data["frontal_area_m2"],
        air_density_kg_m3=data["air_density_kg_m3"],
        gravity_m_s2=data["gravity_m_s2"],
        drivetrain_efficiency=data["drivetrain_efficiency"],
        auxiliary_power_kw=data["auxiliary_power_kw"],
        usable_battery_capacity_kwh=data["usable_battery_capacity_kwh"],
        regen_efficiency=data["regen_efficiency"],
        max_regen_power_kw=data["max_regen_power_kw"],
        regen_min_speed_kmh=data["regen_min_speed_kmh"],
        rotational_inertia_factor=data["rotational_inertia_factor"],
    )


def compute_scenario_physics(scenario: dict[str, Any], vehicle: VehicleConfig) -> EnergyOutputs:
    """Steady-speed physics, or a simulated drive cycle when a traffic profile is selected."""
    profile = scenario.get("traffic_profile") or STEADY
    if profile == STEADY or scenario["duration_minutes"] <= 0:
        return compute_energy(
            EnergyInputs(
                speed_kmh=scenario["speed_kmh"],
                gradient_percent=scenario["gradient_percent"],
                duration_minutes=scenario["duration_minutes"],
            ),
            vehicle,
        )
    seed = scenario.get("traffic_seed")
    trace = generate_speed_trace(
        profile,
        scenario["speed_kmh"],
        scenario["duration_minutes"],
        seed=DEFAULT_TRAFFIC_SEED if seed is None else seed,
    )
    return compute_drive_cycle_energy(trace, scenario["gradient_percent"], vehicle)


def _traffic_summary(scenario: dict[str, Any], physics: EnergyOutputs) -> dict[str, Any]:
    profile = scenario.get("traffic_profile") or STEADY
    speed = scenario["speed_kmh"]
    stats = physics.cycle_stats
    if stats is None:
        return {
            "profile": profile,
            "data_source": "simulated",
            "is_real_world_data": False,
            "description": "Constant speed for the whole duration (no traffic variation)."
            if profile == STEADY
            else TRAFFIC_PROFILES[profile].description,
            "seed": None,
            "target_speed_kmh": speed,
            "average_speed_kmh": speed,
            "max_speed_kmh": speed,
            "stop_count": 0,
            "idle_time_s": scenario["duration_minutes"] * 60.0 if speed == 0 else 0.0,
            "max_acceleration_m_s2": 0.0,
            "max_deceleration_m_s2": 0.0,
            "rms_acceleration_m_s2": 0.0,
            "time_step_s": None,
            "note": SIMULATED_TRAFFIC_NOTE,
        }
    seed = scenario.get("traffic_seed")
    return {
        "profile": profile,
        "data_source": "simulated",
        "is_real_world_data": False,
        "description": TRAFFIC_PROFILES[profile].description,
        "seed": DEFAULT_TRAFFIC_SEED if seed is None else seed,
        "target_speed_kmh": speed,
        "average_speed_kmh": stats.average_speed_kmh,
        "max_speed_kmh": stats.max_speed_kmh,
        "stop_count": stats.stop_count,
        "idle_time_s": stats.idle_time_s,
        "max_acceleration_m_s2": stats.max_acceleration_m_s2,
        "max_deceleration_m_s2": stats.max_deceleration_m_s2,
        "rms_acceleration_m_s2": stats.rms_acceleration_m_s2,
        "time_step_s": stats.time_step_s,
        "note": SIMULATED_TRAFFIC_NOTE,
    }


def _remaining_range(remaining_kwh: float, consumption: Optional[float]) -> tuple[Optional[float], str]:
    if consumption is None:
        return None, "Remaining range unavailable: trip distance is zero, so consumption is undefined."
    if consumption <= 0:
        return None, "Remaining range unavailable: net consumption is not positive (net regeneration on this trip)."
    return remaining_kwh / consumption * 100.0, (
        f"Estimate only: remaining battery energy at this trip's simulated average of {consumption:.2f} kWh/100 km."
    )


def merge_vehicle_params(overrides: Optional[dict]) -> dict:
    base = default_vehicle_dict()
    if overrides:
        for key, value in overrides.items():
            if value is not None and key in base:
                base[key] = value
    return base


class SimulationService:
    def __init__(self, history: HistoryStore, thresholds: Optional[WarningThresholds] = None) -> None:
        self.history = history
        self.thresholds = thresholds or WarningThresholds()

    def run_simulation(
        self,
        scenario: dict[str, Any],
        *,
        store: bool = True,
        baseline_physics: Optional[Any] = None,
        baseline_gradient: Optional[float] = None,
    ) -> dict[str, Any]:
        sim_id = str(uuid.uuid4())
        vehicle_dict = merge_vehicle_params(scenario.get("vehicle_parameters"))
        vehicle = _vehicle_from_dict(vehicle_dict)

        speed = scenario["speed_kmh"]
        gradient = scenario["gradient_percent"]
        duration = scenario["duration_minutes"]
        initial_soc = scenario["initial_soc_percent"]
        battery_temp = scenario["battery_temperature_c"]
        road_surface = scenario.get("road_surface", "dry")
        obstacle_m = scenario.get("obstacle_distance_m")
        obstacle_source = scenario.get("obstacle_source")

        traffic_profile = scenario.get("traffic_profile") or STEADY

        physics = compute_scenario_physics(scenario, vehicle)
        battery = compute_battery_state(
            BatteryInputs(
                initial_soc_percent=initial_soc,
                usable_battery_capacity_kwh=vehicle.usable_battery_capacity_kwh,
                requested_energy_kwh=physics.requested_energy_kwh,
                energy_steps_kwh=physics.energy_steps_kwh,
                step_durations_s=physics.step_durations_s,
            )
        )
        range_km, range_note = _remaining_range(battery.remaining_energy_kwh, physics.consumption_kwh_per_100km)
        traffic = _traffic_summary(scenario, physics)

        battery_state = battery.battery_state
        if not battery.battery_depleted and battery.final_soc_percent < self.thresholds.low_soc_warning_percent:
            battery_state = BatteryState.LOW

        events = generate_events(
            battery_temperature_c=battery_temp,
            obstacle_distance_m=obstacle_m,
            final_soc_percent=battery.final_soc_percent,
            battery_depleted=battery.battery_depleted,
            thresholds=self.thresholds,
            elapsed_simulation_minutes=duration,
        )

        terminal_status = resolve_final_status(events)
        recommendations = build_recommendations(
            physics=physics,
            gradient_percent=gradient,
            speed_kmh=speed,
            road_surface=road_surface,
            events=events,
            baseline_physics=baseline_physics,
            baseline_gradient_percent=baseline_gradient,
        )

        result = {
            "simulation_id": sim_id,
            "scenario_name": scenario.get("scenario_name"),
            "status": terminal_status.value,
            "execution_trace": {
                "previous_status": SimulationStatus.RUNNING.value,
                "terminal_status": terminal_status.value,
            },
            "inputs": {
                "speed_kmh": speed,
                "initial_soc_percent": initial_soc,
                "battery_temperature_c": battery_temp,
                "gradient_percent": gradient,
                "road_surface": road_surface,
                "obstacle_distance_m": obstacle_m,
                "obstacle_source": obstacle_source,
                "duration_minutes": duration,
                "traffic_profile": traffic_profile,
                "traffic_seed": scenario.get("traffic_seed"),
            },
            "vehicle_parameters": vehicle_dict,
            "physics": {
                "road_angle_rad": physics.road_angle_rad,
                "road_angle_deg": physics.road_angle_deg,
                "road_surface_energy_effect": ROAD_SURFACE_ENERGY_EFFECT,
                "rolling_resistance_force_n": physics.rolling_resistance_force_n,
                "aerodynamic_drag_force_n": physics.aerodynamic_drag_force_n,
                "grade_resistance_force_n": physics.grade_resistance_force_n,
                "tractive_force_n": physics.tractive_force_n,
                "longitudinal_acceleration_m_s2": physics.longitudinal_acceleration_m_s2,
                "wheel_power_kw": physics.wheel_power_kw,
                "battery_power_kw": physics.battery_power_kw,
                "requested_energy_kwh": physics.requested_energy_kwh,
                "distance_km": physics.distance_km,
                "consumption_kwh_per_100km": physics.consumption_kwh_per_100km,
                "consumption_unavailable_reason": physics.consumption_unavailable_reason,
                "aggregation": physics.aggregation,
                "traction_energy_kwh": physics.traction_energy_kwh,
                "regenerated_energy_kwh": physics.regenerated_energy_kwh,
                "friction_braking_energy_kwh": physics.friction_braking_energy_kwh,
                "auxiliary_energy_kwh": physics.auxiliary_energy_kwh,
                "peak_battery_power_kw": physics.peak_battery_power_kw,
                "peak_regen_power_kw": physics.peak_regen_power_kw,
            },
            "battery": {
                "initial_soc_percent": battery.initial_soc_percent,
                "final_soc_percent": battery.final_soc_percent,
                "usable_battery_capacity_kwh": battery.usable_battery_capacity_kwh,
                "available_energy_kwh": battery.available_energy_kwh,
                "requested_energy_kwh": battery.requested_energy_kwh,
                "energy_drawn_kwh": battery.energy_drawn_kwh,
                "energy_supplied_kwh": battery.energy_supplied_kwh,
                "battery_depleted": battery.battery_depleted,
                "battery_state": battery_state.value,
                "depletion_note": battery.depletion_note,
                "trip_completed_in_model": battery.trip_completed_in_model,
                "remaining_energy_kwh": battery.remaining_energy_kwh,
                "estimated_remaining_range_km": range_km,
                "remaining_range_note": range_note,
                "regen_energy_not_stored_kwh": battery.regen_energy_not_stored_kwh,
                "depletion_elapsed_minutes": battery.depletion_elapsed_minutes,
            },
            "telemetry": {
                "data_quality": "simulated",
                "speed_kmh": speed,
                "battery_temperature_c": battery_temp,
                "initial_soc_percent": battery.initial_soc_percent,
                "final_soc_percent": battery.final_soc_percent,
                "wheel_power_kw": physics.wheel_power_kw,
                "battery_power_kw": physics.battery_power_kw,
                "requested_energy_kwh": physics.requested_energy_kwh,
                "energy_supplied_kwh": battery.energy_supplied_kwh,
                "distance_km": physics.distance_km,
                "consumption_kwh_per_100km": physics.consumption_kwh_per_100km,
                "gradient_percent": gradient,
                "road_surface": road_surface,
                "status": terminal_status.value,
                "traffic_profile": traffic_profile,
                "traffic_data_source": "simulated",
                "estimated_remaining_range_km": range_km,
            },
            "traffic": traffic,
            "events": [
                {
                    "event_id": e.event_id,
                    "event_type": e.event_type.value,
                    "severity": e.severity.value,
                    "triggering_value": e.triggering_value,
                    "threshold": e.threshold,
                    "unit": e.unit,
                    "message": e.message,
                    "suggested_action": e.suggested_action,
                    "elapsed_simulation_minutes": e.elapsed_simulation_minutes,
                }
                for e in events
            ],
            "recommendations": [
                {
                    "category": r.category,
                    "priority": r.priority,
                    "title": r.title,
                    "explanation": r.explanation,
                    "relevant_measurement_value": r.relevant_measurement_value,
                    "relevant_measurement_unit": r.relevant_measurement_unit,
                    "relevant_measurement": r.relevant_measurement,
                    "suggested_action": r.suggested_action,
                    "reason": r.reason,
                    "evaluation_hint": r.evaluation_hint,
                }
                for r in recommendations
            ],
            "path_planning_integration": {
                "contract_version": PATH_PLANNING_INTEGRATION_DOC["contract_version"],
                "status": PATH_PLANNING_INTEGRATION_DOC["status"],
                "obstacle_source": obstacle_source,
                "message": PATH_PLANNING_INTEGRATION_DOC["message"],
            },
            "assumptions": list(MODEL_ASSUMPTIONS),
            "limitations": list(MODEL_LIMITATIONS),
            "units": {
                "speed": "km/h",
                "distance": "km",
                "energy": "kWh",
                "power": "kW",
                "force": "N",
                "angle": "deg and rad",
                "soc": "%",
                "temperature": "°C",
                "road_surface": "category",
            },
        }

        if store:
            self.history.add(sim_id, result)
        return result
